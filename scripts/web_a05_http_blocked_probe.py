#!/usr/bin/env python3
"""Read-only + malformed POST probe for the Web V3 QA Apps Script.
No valid student submission can be generated by this file.
Requires the QA endpoint to be blocked before the probe starts.
"""
import json
import sys
import uuid
from urllib.parse import urlencode
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError

URL = "https://script.google.com/macros/s/AKfycbzW5ekgFdlyayf14Pi-uX7uBygxRMr2FqJS6hrQeKxsdj-WdVcyT0JI8vuzhVyT5L_W/exec"
EXPECTED = "Web web-notas-3.0.1-candidata — QA — recebimento bloqueado — matrícula obrigatória, maior nota, média automática"

def fetch(req):
    with urlopen(req, timeout=30) as response:
        return response.read(250_000).decode("utf-8", errors="replace")

def main():
    try:
        first = fetch(Request(URL, method="GET")).strip()
        if first != EXPECTED:
            print("NO_GO: GET nao confirmou V3 QA bloqueado:", repr(first[:200]))
            return 2
        print("G0 PASS: GET confirma V3.0.1 QA bloqueado")
        nonce = "qa-blocked-" + str(uuid.uuid4())
        # Intencionalmente invalido: jamais contem identidade, nota, evidencia ou matricula.
        encoded = urlencode({"nonce": nonce, "payload": "{}"}).encode("utf-8")
        req = Request(URL, data=encoded, method="POST",
                      headers={"Content-Type": "application/x-www-form-urlencoded"})
        body = fetch(req)
        if "top.postMessage(" not in body or nonce not in body or '"ok":false' not in body:
            print("NO_GO: POST nao retornou recibo estruturado de rejeicao")
            return 3
        if "Recebimento QA V3 bloqueado." not in body:
            print("NO_GO: POST nao confirmou bloqueio do receptor")
            return 4
        print("G1 PASS: POST invalido rejeitado pelo Apps Script bloqueado")
        final = fetch(Request(URL, method="GET")).strip()
        if final != EXPECTED:
            print("NO_GO: estado final do receptor nao confirmado como bloqueado")
            return 5
        print("G2 PASS: GET final confirma recebimento ainda bloqueado")
        print("HTTP_BLOCKED_QA_PASS_SCOPED: sem submissao valida; readback Sheet necessario")
        return 0
    except (URLError, HTTPError, TimeoutError) as exc:
        print("INCONCLUSIVO_REDE:", str(exc)[:300])
        return 6

if __name__ == "__main__":
    sys.exit(main())
